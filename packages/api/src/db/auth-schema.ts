/**
 * Better-Auth's own tables — `auth_user`, `auth_session`, `auth_account`, `auth_verification`.
 *
 * WHERE THIS CAME FROM. `npx @better-auth/cli generate` was run once against a config mirroring
 * the real composition (`emailOTP`, `bearer({requireSignature:true})`, `oneTimeToken`,
 * `drizzleAdapter(db,{provider:"pg"})`, the `auth_*` `modelName`s below) and then HAND-CORRECTED
 * against the schema the installed `better-auth` runtime actually builds
 * (`@better-auth/core/db/get-tables.mjs`, via `buildAuthTables`). It was last re-read against
 * `1.7.14`.
 *
 * ACCOUNT IDENTITY IS `(providerId, accountId)` AGAIN. `1.7.0`–`1.7.2` (this file was first cut
 * against `1.7.1`) scoped account identity by a synthetic, required `issuer` column and a unique
 * `(issuer, accountId)` index. `1.7.3` reverted that to the 1.6 shape — accounts are recognized by
 * `(providerId, accountId)` and `issuer` is never written — and since `1.7.3` the adapter validates
 * this schema at initialization and rejects every auth request on a mismatch ("Required columns
 * Better Auth never writes: account.issuer"). Migration `0018` follows the library's upgrade guide
 * ("Account identity keeps the provider key"):
 *
 *   1. `auth_account.issuer` is NULLABLE, not dropped. New rows leave it NULL. Keeping the column
 *      is what keeps a rollback to a `1.7.1` build working — that runtime still writes it — and
 *      dropping it is separate cleanup for once the `1.7.1` image is out of the rollback window.
 *   2. The unique index moves from `(issuer, accountId)` to `(providerId, accountId)`: the key the
 *      runtime now looks accounts up by, and the constraint that keeps a provider identity arriving
 *      twice from linking twice (`integration/account-linking.test.ts`). It cannot collide with
 *      existing rows, because `issuer` was derived from `providerId` one-to-one
 *      (`local:oauth:<providerId>`), so the old index already implied this one.
 *
 * None of the three plugins wired in (`emailOTP`, `bearer`, `oneTimeToken`) add a table or a field
 * of their own — verified by reading their plugin definitions; only `emailOTP`'s OpenAPI response
 * schemas contain the word "schema", not a DB one. So these four tables are the complete surface.
 *
 * WHY THIS FILE IS NOT REGENERATED BY `db:generate`. `drizzle-kit generate` diffs THIS file's
 * `pgTable` calls against the migrations directory, same as every other table in `schema.ts` — it
 * does not know or care that these definitions originated from Better-Auth. There is no ongoing
 * codegen step; a future Better-Auth bump is reviewed by hand against `get-tables.mjs` again, the
 * same way this first cut was.
 *
 * WHY `public` SCHEMA, WHY THESE `modelName`s, WHY `auth_user_id` HAS NO FK: see
 * `plan §0 #3, #3a` / `docs/data-model.md`. In short: the E2E runtime role is granted
 * `ON ALL TABLES IN SCHEMA public` only, so a `schemaName:"auth"` table would be invisible to it;
 * and `accounts.auth_user_id` (in `schema.ts`) deliberately carries no FK to `auth_user.id` because
 * an `accounts` row must outlive an `auth_user` row — `audit_log` points at the former, never the
 * latter.
 *
 * WHY THESE FOUR TABLES CASCADE ON `auth_user_id`/`user_id` WHILE `accounts` DOES NOT: these tables
 * belong to Better-Auth, not to this application's data model. A session or a linked provider
 * account has no meaning once its `auth_user` is gone, so cascading here is simply keeping
 * Better-Auth's own referential integrity — it is not the same design question as the app's
 * `accounts` table, which is deliberately outlived by its own foreign referrers.
 */
import { boolean, index, pgTable, text, timestamp, uniqueIndex } from "drizzle-orm/pg-core";

// ── auth_user ──────────────────────────────────────────────────────────────────
export const authUser = pgTable("auth_user", {
  /** Better-Auth's default id generation (a CSPRNG string minted in JS) — see plan §0 #3b. */
  id: text().primaryKey(),
  name: text().notNull(),
  /** Lower-cased by Better-Auth before it ever reaches the adapter; not re-enforced here. */
  email: text().notNull().unique(),
  emailVerified: boolean().notNull().default(false),
  image: text(),
  createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
});

// ── auth_session ───────────────────────────────────────────────────────────────
export const authSession = pgTable(
  "auth_session",
  {
    id: text().primaryKey(),
    expiresAt: timestamp({ withTimezone: true }).notNull(),
    /**
     * The opaque bearer credential. UNIQUE is what `SessionService.verify` (plan §2 P2) leans on —
     * signing out deletes the row, so the very next lookup by token is a clean miss, not a stale
     * hit against a duplicate.
     */
    token: text().notNull().unique(),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    ipAddress: text(),
    userAgent: text(),
    userId: text()
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
  },
  (t) => [index("ix_auth_session_user").on(t.userId)],
);

// ── auth_account ───────────────────────────────────────────────────────────────
export const authAccount = pgTable(
  "auth_account",
  {
    id: text().primaryKey(),
    /**
     * The provider-scoped subject. On its own it is NOT globally unique — `(providerId, accountId)`
     * is the real key; see the header comment.
     */
    accountId: text().notNull(),
    providerId: text().notNull(),
    /**
     * LEGACY, written only by `1.7.0`–`1.7.2` (`local:oauth:google`, …). Current runtimes never set
     * it, so it is nullable and nothing reads it; it stays only so a rollback to a `1.7.1` build
     * keeps working. See the header comment.
     */
    issuer: text(),
    userId: text()
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
    accessToken: text(),
    refreshToken: text(),
    idToken: text(),
    accessTokenExpiresAt: timestamp({ withTimezone: true }),
    refreshTokenExpiresAt: timestamp({ withTimezone: true }),
    /** Accumulated OAuth grant, comma-separated — the union of every scope ever consented to. */
    scope: text(),
    /** Populated only for the (unused, per plan §0 #2 — OTP only, no password) credential provider. */
    password: text(),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // THE constraint that keeps one provider identity linked once — see the header comment.
    uniqueIndex("ux_auth_account_provider_account").on(t.providerId, t.accountId),
    index("ix_auth_account_user").on(t.userId),
  ],
);

// ── auth_verification ─────────────────────────────────────────────────────────
/** OTP codes and any other short-lived, single-use verification value Better-Auth mints. */
export const authVerification = pgTable(
  "auth_verification",
  {
    id: text().primaryKey(),
    /** What is being verified — an email address for `emailOTP`. */
    identifier: text().notNull(),
    value: text().notNull(),
    expiresAt: timestamp({ withTimezone: true }).notNull(),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("ix_auth_verification_identifier").on(t.identifier)],
);

export type AuthUserRow = typeof authUser.$inferSelect;
export type AuthSessionRow = typeof authSession.$inferSelect;
export type AuthAccountRow = typeof authAccount.$inferSelect;
export type AuthVerificationRow = typeof authVerification.$inferSelect;
